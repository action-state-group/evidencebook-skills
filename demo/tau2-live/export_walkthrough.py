"""Write the walkthrough's data file from one finished case.

    uv run python export_walkthrough.py CASE_DIR [--out walkthrough/data.js]

The walkthrough page (walkthrough/index.html) plays the case step by step from
this file only: the turns as they were said, the records as they were sealed,
the spans as they were exported, the evaluator's signed verdict and the two
bundles with their verify results. It invents nothing; a file the case lacks is
left out and the page says so.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent


def load(path: Path, default=None):
    return json.loads(path.read_text()) if path.exists() else default


def lines(path: Path) -> list[dict]:
    return [json.loads(x) for x in path.read_text().splitlines() if x.strip()] if path.exists() else []


def capsule_id(path: Path) -> str | None:
    """The capsule id of a record file capsulectl wrote ({record: {record: {capsule_id}}} or a bare Capsule)."""
    data = load(path)
    if not data:
        return None
    for keys in (("record", "record", "capsule_id"), ("record", "capsule_id"), ("capsule_id",)):
        v = data
        for k in keys:
            v = v.get(k) if isinstance(v, dict) else None
        if isinstance(v, str):
            return v
    return None


def export(case_dir: Path) -> dict:
    meta = load(case_dir / "case.json")
    task = load(case_dir / "task.json")
    report = load(case_dir / "report" / "summary.json")
    spans = []
    for s in lines(case_dir / "spans.jsonl"):
        spans.append({"name": s["name"], "trace_id": s["context"]["trace_id"].removeprefix("0x"),
                      "span_id": s["context"]["span_id"].removeprefix("0x"),
                      "parent_id": (s.get("parent_id") or "").removeprefix("0x") or None,
                      "service": s["resource"]["attributes"].get("service.name"),
                      "start": s["start_time"], "end": s["end_time"],
                      "capsule_id": s["attributes"].get("aac.capsule_id")})
    bundles = {}
    for level, b in ((report or {}).get("bundles") or {}).items():
        rep = b.get("report") or {}
        bundles[level] = {"file": b["file"], "audience": rep.get("audience"), "rows_state": rep.get("rows_state"),
                          "rows": [{"row": r.get("row") or r.get("id"), "status": r.get("status")} for r in rep.get("rows") or []],
                          "verify": b["verify"].get("verdict"), "exit_code": b["verify"].get("exit_code"),
                          "bundle_digest": b["verify"].get("bundle_digest")}
    return {
        "case": {"book": meta["book"], "window": meta.get("window"), "deal_id": meta["deal_id"], "task_id": meta["task_id"], "opened_at": meta["opened_at"],
                 "reason_for_call": task["user_scenario"]["instructions"]["reason_for_call"].strip()},
        "records": {"offer": capsule_id(case_dir / "offer.json"), "agreement": capsule_id(case_dir / "agree.json")},
        "turns": load(case_dir / "transcript.json", []),
        "tool_calls": lines(case_dir / "tool_calls.jsonl"),
        "spans": spans,
        "evaluation": load(case_dir / "evaluation.json"),
        "report": {"book": (report or {}).get("book"), "bundles": bundles} if report else None,
    }


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("case_dir", type=Path)
    p.add_argument("--out", type=Path, default=HERE / "walkthrough" / "data.js")
    a = p.parse_args()
    data = export(a.case_dir.resolve())
    a.out.write_text("// Generated by export_walkthrough.py from one recorded live case; do not edit.\n"
                     "window.TAU2_CASE = " + json.dumps(data, indent=1) + ";\n")
    print(a.out)


if __name__ == "__main__":
    main()
